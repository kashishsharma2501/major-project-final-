/** All active skills (shown on platform) */
export const activeSkills = skillCatalogue.filter((s) => s.isActive);

/** Featured skills (shown on landing page and explore prominently) */
export const featuredSkills = skillCatalogue.filter((s) => s.isFeatured && s.isActive);

/** Skills with verified market evidence */
export const verifiedSkills = skillCatalogue.filter(
  (s) => s.evidenceStatus === 'verified'
);

/** Skills needing local validation */
export const projectCandidates = skillCatalogue.filter(
  (s) => s.evidenceStatus === 'needs_validation'
);

/** Get unique categories */
export const catalogueCategories = [
  ...new Set(skillCatalogue.map((s) => s.category)),
];

/** Get unique fields */
export const catalogueFields = [
  ...new Set(skillCatalogue.map((s) => s.field)),
];

/** Get skill by ID */
export const getCatalogueSkillById = (id: string) =>
  skillCatalogue.find((s) => s.id === id);

/** Get skills by category */
export const getSkillsByCategory = (category: string) =>
  skillCatalogue.filter((s) => s.category === category && s.isActive);

/** Stats for admin dashboard */
export const catalogueStats = {
  total: skillCatalogue.length,
  verified: verifiedSkills.length,
  active: activeSkills.length,
  featured: featuredSkills.length,
  needsValidation: projectCandidates.length,
};
